// Regenerates src/endpoints.ts from the live Invezgo OpenAPI spec: `npm run gen`.
import { writeFileSync } from "node:fs";

const SPEC_URL = process.argv[2] ?? "https://api.invezgo.com/openapi.json";
const spec = await (await fetch(SPEC_URL, { headers: { "User-Agent": "Invezgo Claw" } })).json();

const clip = (s, n) => {
  const t = (s ?? "").replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n - 1) + "…" : t;
};
// Descriptions are "Indonesian\n---\n[English]\nEnglish"; keep the English half when present.
const english = (d = "") => (d.includes("[English]") ? d.split("[English]").pop() : d).trim();
const resolve = (schema) =>
  schema?.$ref ? spec.components.schemas[schema.$ref.split("/").pop()] : schema;

const compactSchema = (schema, depth = 0) => {
  schema = resolve(schema);
  if (!schema || depth > 2) return schema?.type ?? "any";
  if (schema.type === "array") return [compactSchema(schema.items, depth + 1)];
  if (schema.properties) {
    const req = new Set(schema.required ?? []);
    return Object.fromEntries(
      Object.entries(schema.properties).map(([k, v]) => {
        const r = resolve(v);
        const desc = clip(english(r.description), 120);
        const type = r.properties || r.type === "array" ? compactSchema(r, depth + 1) : r.enum ? r.enum.join("|") : r.type;
        return [k + (req.has(k) ? "*" : ""), desc ? { type, desc } : type];
      }),
    );
  }
  return schema.enum ? schema.enum.join("|") : schema.type ?? "any";
};

const endpoints = [];
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    const desc = english(op.description);
    const body = op.requestBody?.content?.["application/json"];
    endpoints.push({
      method: method.toUpperCase(),
      path,
      tag: op.tags?.[0] ?? "Other",
      summary: clip(op.summary || desc.split("\n").find((l) => l.trim()), 160),
      description: clip(desc, 1500),
      params: (op.parameters ?? []).map((p) => ({
        name: p.name,
        in: p.in,
        required: Boolean(p.required),
        description: clip(p.description, 200),
        ...(resolve(p.schema)?.enum ? { enum: resolve(p.schema).enum } : {}),
      })),
      ...(body ? { body: compactSchema(body.schema), bodyExample: body.example } : {}),
    });
  }
}

writeFileSync(
  new URL("../src/endpoints.ts", import.meta.url),
  `// Generated by scripts/gen-catalog.mjs from ${SPEC_URL} (spec v${spec.info.version}). Do not edit.\n` +
    `export const SPEC_VERSION = ${JSON.stringify(spec.info.version)};\n` +
    `export const ENDPOINTS: Endpoint[] = ${JSON.stringify(endpoints, null, 1)};\n` +
    `export type Endpoint = { method: string; path: string; tag: string; summary: string; description: string; ` +
    `params: { name: string; in: string; required: boolean; description: string; enum?: unknown[] }[]; body?: unknown; bodyExample?: unknown };\n`,
);
console.log(`Wrote ${endpoints.length} endpoints.`);
